import assert from 'node:assert/strict';
export async function verifyTouchControls({call,evaluate,until,delay,screenshot,url,openSandbox,click}){
 await call('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
 await call('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:5});
 await call('Page.navigate',{url});await openSandbox();
 assert(await evaluate('document.documentElement.scrollWidth<=window.innerWidth'));
 assert.equal(await evaluate("document.querySelectorAll('.tool-bar button').length"),6);
 const center=await evaluate("(()=>{const r=document.querySelector('.world canvas').getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2,z:Math.min(r.width,r.height)/3072*.93};})()");
 const finger=(id,x,y)=>({id,x,y,radiusX:2,radiusY:2});
 const touch=(type,touchPoints)=>call('Input.dispatchTouchEvent',{type,touchPoints});
 const tap=async(x,y)=>{await touch('touchStart',[finger(1,x,y)]);await touch('touchEnd',[]);await delay(100);};
 const tool=async name=>{await click(name,"document.querySelector('.tool-bar')");};
 await tap(center.x,center.y);await until('window.__cellhubFrame.cells.length===12');
 await tool('Диагностика');await tap(center.x,center.y);await until("document.querySelector('.cell-details')?.textContent.includes('Масса')");
 await tool('Поместить');
 await touch('touchStart',[finger(1,center.x-35,center.y),finger(2,center.x+35,center.y)]);
 await touch('touchMove',[finger(1,center.x-45,center.y),finger(2,center.x+85,center.y)]);
 await touch('touchEnd',[finger(1,center.x-45,center.y)]);await touch('touchEnd',[]);await delay(100);
 assert.equal(await evaluate('window.__cellhubFrame.cells.length'),12,'pinch must not place a cell');
 await tap(center.x,center.y);await until('window.__cellhubFrame.cells.length===24');
 const rows=await evaluate('Array.from(window.__cellhubFrame.cells)');
 assert(Math.abs(rows[13]-(1536-20/(center.z*130/70)))<2,'pinch preserves moving midpoint anchor');
 await touch('touchStart',[finger(1,center.x-65,center.y),finger(2,center.x+65,center.y)]);
 await touch('touchMove',[finger(1,center.x-35,center.y),finger(2,center.x+35,center.y)]);
 await touch('touchEnd',[finger(1,center.x-35,center.y)]);await touch('touchMove',[finger(1,center.x-15,center.y+10)]);await touch('touchEnd',[]);
 await touch('touchStart',[finger(1,center.x,center.y)]);await touch('touchCancel',[]);await delay(100);
 assert.equal(await evaluate('window.__cellhubFrame.cells.length'),24);
 await tool('Обзор');await touch('touchStart',[finger(1,center.x,center.y)]);await touch('touchMove',[finger(1,center.x+40,center.y+25)]);await touch('touchEnd',[]);
 assert.equal(await evaluate('window.__cellhubFrame.cells.length'),24);
 await screenshot('work/cellhub-mobile-controls.png');
 await click('Геном',"document.querySelector('.tabs')");await evaluate("document.querySelector('.genome-editor').scrollIntoView({block:'start'})");
 assert((await evaluate('window.scrollY'))>0,'editor remains scrollable outside microscope');
 assert(await evaluate('document.documentElement.scrollWidth<=window.innerWidth'));
 await screenshot('work/cellhub-mobile-editor.png');
 await call('Emulation.setTouchEmulationEnabled',{enabled:false});
 await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1080,deviceScaleFactor:1,mobile:false});
 console.log('PASS: Home mobile entry, tools, tap/inspect, pinch/pan, cancellation and editor scrolling');
}
